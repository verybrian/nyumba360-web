<script setup>
import { ref, onMounted, nextTick } from 'vue'
import { useRouter } from 'vue-router'
import { apiFetch } from '@/utils/api'

const router = useRouter()

const goToDashboard = () => router.push('/d/')
const goToLogin = () => router.push('/login')
const goToSignup = () => router.push('/signup')

const isAuthenticated = ref(false)

async function checkAuth() {
  try {
    const res = await apiFetch('/api/properties/')
    isAuthenticated.value = res.ok
  } catch {
    isAuthenticated.value = false
  }
}

function setupPricingToggle() {
  const toggleBtns = document.querySelectorAll('.toggle-btn')

  toggleBtns.forEach((btn) => {
    btn.addEventListener('click', () => {
      toggleBtns.forEach((b) => b.classList.remove('active'))
      btn.classList.add('active')

      const cycle = btn.dataset.cycle

      document.querySelectorAll('.price-display').forEach((el) => {
        el.textContent = el.dataset[cycle]
      })
      ;['monthly', 'biannual', 'annual'].forEach((c) => {
        document.querySelectorAll(`.cadence-${c}`).forEach((el) => {
          el.style.display = c === cycle ? '' : 'none'
        })
      })

      document.querySelectorAll('.savings-badge').forEach((el) => {
        if (el.classList.contains('savings-biannual')) {
          el.style.display = cycle === 'biannual' ? 'inline-flex' : 'none'
        } else if (el.classList.contains('savings-annual')) {
          el.style.display = cycle === 'annual' ? 'inline-flex' : 'none'
        }
      })
    })
  })
}

function filterListings() {
  const loc = document.getElementById('filter-location').value
  const type = document.getElementById('filter-type').value
  const priceVal = document.getElementById('filter-price').value
  const furnish = document.getElementById('filter-furnish').value

  const maxPrice = priceVal ? parseInt(priceVal) : Infinity

  const cards = document.querySelectorAll('#listings-grid .listing-card')
  let visible = 0

  cards.forEach((card) => {
    const match =
      (!loc || card.dataset.location === loc) &&
      (!type || card.dataset.type === type) &&
      parseInt(card.dataset.price) <= maxPrice &&
      (!furnish || card.dataset.furnish === furnish)

    card.style.display = match ? '' : 'none'

    if (match) visible++
  })

  document.getElementById('results-count').textContent = visible
  document.getElementById('no-results').style.display = visible === 0 ? 'block' : 'none'
}

function setupFavouriteToggle() {
  document.querySelectorAll('.listing-fav').forEach((btn) => {
    btn.addEventListener('click', (e) => {
      e.stopPropagation()
      btn.textContent = btn.textContent.trim() === '🤍' ? '❤️' : '🤍'
    })
  })
}

function setupScrollReveal() {
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((e) => {
        if (e.isIntersecting) {
          e.target.classList.add('visible')
          observer.unobserve(e.target)
        }
      })
    },
    { threshold: 0.1 },
  )

  document.querySelectorAll('.reveal').forEach((el) => observer.observe(el))
}

function revealHero() {
  setTimeout(() => {
    document.querySelectorAll('#hero .reveal').forEach((el) => {
      el.classList.add('visible')
    })
  }, 80)
}

onMounted(async () => {
  await checkAuth()

  await nextTick()

  setupPricingToggle()
  setupFavouriteToggle()
  setupScrollReveal()
  revealHero()
})

window.filterListings = filterListings
</script>

